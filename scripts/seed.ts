import dotenv from 'dotenv';
import { cleanupVisitorData } from '../lib/demo/cleanup';
import { seedDemoData } from '../lib/demo/seed';
import { getAppEnv, getCoreEnv, getDemoEnv } from '../lib/env';
import { getLedger } from '../lib/ledger';

dotenv.config({ path: ['.env.local', '.env'] });

const flags = new Set(process.argv.slice(2));
const unknown = [...flags].filter((flag) => flag !== '--reset');
if (unknown.length) throw new Error(`Unknown option(s): ${unknown.join(', ')}. Supported: --reset`);

const { databaseUrl } = getCoreEnv();
const { appUrl } = getAppEnv();
const databaseHost = new URL(databaseUrl).host;
const isLocalDatabase = /^(localhost|127\.0\.0\.1)(:|$)/.test(databaseHost);

console.log(`Seeding database host: ${databaseHost}`);
if (!isLocalDatabase && /localhost|127\.0\.0\.1/.test(appUrl)) {
  console.warn(
    `Warning: NEXT_PUBLIC_APP_URL is ${appUrl}, but the database is remote. Certificate QR codes embed this origin, ` +
      'and PDFs regenerated by the deployed app will not match the stored hashes unless it uses the same value. ' +
      'Set NEXT_PUBLIC_APP_URL to the deployed origin before seeding a hosted database.',
  );
}

// Loaded after dotenv because the Payload config reads the environment on import.
const [{ default: config }, { getPayload }] = await Promise.all([import('../payload.config'), import('payload')]);
const payload = await getPayload({ config });

try {
  if (flags.has('--reset')) {
    const removed = await cleanupVisitorData(payload);
    console.log(`Removed visitor data: ${removed.verifiedSkills} skills, ${removed.versions} versions, ${removed.passports} passports.`);
  }

  const demo = getDemoEnv();
  const summary = await seedDemoData({
    payload,
    ledger: getLedger(payload),
    verifyBaseUrl: appUrl,
    demo: demo.enabled ? demo : undefined,
    log: console.log,
  });

  console.log('\nSeed complete.');
  console.log(`  Skills:      ${summary.skills.created} created, ${summary.skills.existing} existing`);
  console.log(`  Students:    ${summary.students.created} created, ${summary.students.existing} existing`);
  console.log(`  Credentials: ${summary.credentials.issued} issued, ${summary.credentials.existing} already present`);
  if (!demo.enabled) console.log('  Demo accounts were not created because DEMO_MODE is not enabled.');
} finally {
  await payload.destroy();
}
